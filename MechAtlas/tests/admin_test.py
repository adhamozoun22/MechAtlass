    def h(r):
        u=r.request.url
        if '127.0.0.1' in u: return r.continue_()
        if 'supabase-js' in u: return r.fulfill(status=200,body=MOCK,content_type='application/javascript') if lib else r.fulfill(status=404,body='x')
        return r.fulfill(status=200,body='')
    ctx.route('**/*',h)
